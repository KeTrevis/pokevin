"""Copy the game's data and battle core into an isolated extension worker."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def section(source, start, end):
    begin = source.index(start)
    return source[begin:source.index(end, begin)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("bundle", type=Path, help="Original app.<hash>.js from the game")
    parser.add_argument("--build", required=True, help="window.BUILD from the matching boot.js")
    args = parser.parse_args()
    original = args.bundle.read_bytes()
    digest = hashlib.sha256(original).hexdigest()
    if args.bundle.name != f"app.{digest[:10]}.js":
        parser.error("The bundle filename does not match its SHA-256")
    source = original.decode("utf-8")
    data = section(source, "t.POKEDEX=", ",t.I18n=")
    core = section(source, "t.DAYTIME=", ",t.Underground=")
    # These aliases are declared in this build's preamble, outside the copied core.
    wrapper = """// Generated by tools/build_extension_engine.py. Game code belongs to its authors.
// Offline worker only: no DOM, account, network, or persistent storage access.
(() => {
  const e = (text, values) => String(text).replace(/\\{(\\w+)\\}/g, (m, k) => values?.[k] ?? m);
  let snapshotTime = Date.now();
  const t = {
    I18n: { lang: 'fr', t: e }, _t: e,
    Clock: { now: () => snapshotTime },
    addEventListener() {}, dispatchEvent() {},
  };
  const location = { hostname: 'localhost' };
  const localStorage = {
    getItem() { throw new Error('Simulator storage is disabled'); },
    setItem() { throw new Error('Simulator storage is disabled'); },
  };
  const Es = () => 0; // No background timers in the copied core.
  const Za = setTimeout.bind(globalThis);
  const Qn = fn => Za(() => fn(performance.now()), 0);
  const Dn = performance;
  const CustomEvent = class { constructor(type, options) { this.type = type; this.detail = options?.detail; } };
"""
    output = wrapper + data + ";\n" + core + ";\n" + """
  t.setSnapshotTime = value => { snapshotTime = value; };
  globalThis.PokeCatchEngine = t;
})();
"""
    (ROOT / "engine/core.js").write_text(output, encoding="utf-8")
    (ROOT / "engine/version.json").write_text(json.dumps({
        "build": args.build, "bundle": args.bundle.name, "sha256": digest,
    }, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
