"""Copy the game's data and battle core into an isolated extension worker."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def section(source, start, end):
    begin = source.index(start)
    return source[begin:source.index(end, begin)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("bundle", type=Path, help="Original app.<hash>.js from the game")
    parser.add_argument("--build", required=True, help="window.BUILD from the matching boot.js")
    args = parser.parse_args()
    original = args.bundle.read_bytes()
    digest = hashlib.sha256(original).hexdigest()
    if args.bundle.name != f"app.{digest[:10]}.js":
        parser.error("The bundle filename does not match its SHA-256")
    source = original.decode("utf-8")
    namespace_match = re.search(r"([\w$]+)\.POKEDEX=", source)
    if not namespace_match:
        parser.error("Cannot find the game's module namespace")
    namespace = namespace_match.group(1)
    data = section(source, f"{namespace}.POKEDEX=", f",{namespace}.I18n=")
    core = section(source, f"{namespace}.DAYTIME=", f",{namespace}.Underground=")
    encounters = section(source, f"{namespace}.Events=", f",{namespace}.Sfx=")
    # These aliases are declared in this build's preamble, outside the copied core.
    preamble = source[:source.index(f"{namespace}.POKEDEX=")]
    timer_aliases = {}
    for method in ["setTimeout", "setInterval", "requestAnimationFrame"]:
        match = re.search(r"([\w$]+)=([\w$]+)\." + method + r"\.bind\(\2\)", preamble)
        if not match:
            parser.error(f"Cannot find the native {method} alias")
        timer_aliases[method] = match.group(1)
    perf = re.search(r"([\w$]+)=Object.freeze\(\{now:([\w$]+)\.performance.now.bind\(\2\.performance\)\}\)", preamble)
    if not perf:
        parser.error("Cannot find the native performance alias")
    wrapper = """// Generated by tools/build_extension_engine.py. Game code belongs to its authors.
// Offline worker only: no DOM, account, network, or persistent storage access.
(() => {
  const e = (text, values) => String(text).replace(/\\{(\\w+)\\}/g, (m, k) => values?.[k] ?? m);
  let snapshotTime = globalThis.Date.now();
  const SystemDate = globalThis.Date;
  const Date = class extends SystemDate {
    constructor(...args) { super(...(args.length ? args : [snapshotTime])); }
    static now() { return snapshotTime; }
  };
  const t = {
    I18n: { lang: 'fr', t: e }, _t: e,
    Clock: { now: () => snapshotTime },
    addEventListener() {}, dispatchEvent() {},
  };
  const location = { hostname: 'localhost' };
  const localStorage = {
    getItem() { throw new Error('Simulator storage is disabled'); },
    setItem() { throw new Error('Simulator storage is disabled'); },
  };
__ALIASES__
  const CustomEvent = class { constructor(type, options) { this.type = type; this.detail = options?.detail; } };
"""
    aliases = [
        f"  const {timer_aliases['setInterval']} = () => 0; // No background timers in the copied core.",
        f"  const {timer_aliases['setTimeout']} = setTimeout.bind(globalThis);",
        f"  const {timer_aliases['requestAnimationFrame']} = fn => {timer_aliases['setTimeout']}(() => fn(performance.now()), 0);",
        f"  const {perf.group(1)} = performance;",
    ]
    if namespace != "t":
        aliases.append(f"  const {namespace} = t;")
    wrapper = wrapper.replace("__ALIASES__", "\n".join(aliases))
    output = wrapper + data + ";\n" + core + ";\n" + encounters + ";\n" + """
  t.setSnapshotTime = value => { snapshotTime = value; };
  globalThis.PokeCatchEngine = t;
})();
"""
    (ROOT / "engine/core.js").write_text(output, encoding="utf-8")
    (ROOT / "engine/version.json").write_text(json.dumps({
        "build": args.build, "bundle": args.bundle.name, "sha256": digest,
    }, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
